class ComplianceChecklistAgent(ProductionAgent):
    name = "ComplianceChecklistAgent"
    department = "legal"
    system_prompt = """You are a Compliance Officer specializing in GDPR, CCPA, and SOC2.
Generate a practical compliance checklist. For each item: requirement, action needed, risk of non-compliance."""

    async def execute(self, task: str, context: Dict[str, Any] = None) -> AgentOutput:
        try:
            from shared.inter_dept import call_research_dept
            reg_info = await call_research_dept(
                task=f"Current GDPR CCPA SOC2 compliance requirements for: {task}",
                api_keys=(context or {}).get("api_keys"),
                selected_model=(context or {}).get("selected_model"),
            )
        except Exception:
            reg_info = ""
        prompt = f"Generate compliance checklist for: {task}\n\nContext: {reg_info[:2000]}"
        try:
            checklist = await self._ainvoke(prompt)
            return AgentOutput(agent_name=self.name, department=self.department,
                               success=True, content=checklist, metadata={})
        except Exception as e:
            return AgentOutput(agent_name=self.name, department=self.department,
                               success=False, content="", error=str(e), metadata={})


class LegalSynthesizerAgent(ProductionAgent):
    name = "LegalSynthesizerAgent"
    department = "legal"
    system_prompt = "You are a Legal Summary specialist. Combine all legal analysis clearly. Always add the NOT LEGAL ADVICE disclaimer."

    async def execute(self, task: str, context: Dict[str, Any] = None) -> AgentOutput:
        context = context or {}
        parts = [f"# Legal Analysis\n"]
        if context.get("contract_review"):
            parts.append(f"## Contract Review\n{context['contract_review']}\n")
        if context.get("tos_draft"):
            parts.append(f"## Document Draft\n{context['tos_draft']}\n")
        if context.get("compliance_checklist"):
            parts.append(f"## Compliance Checklist\n{context['compliance_checklist']}\n")
        combined = "\n".join(parts)
        try:
            synthesis = await self._ainvoke(f"Synthesize clearly:\n\n{combined[:5000]}")
            return AgentOutput(agent_name=self.name, department=self.department,
                               success=True, content=synthesis + _DISCLAIMER, metadata={})
        except Exception as e:
            return AgentOutput(agent_name=self.name, department=self.department,
                               success=True, content=combined + _DISCLAIMER, error=str(e), metadata={})
